#!/usr/bin/env python3
"""Real Chromium mobile regression for local AI study captain + original Jokbo."""
import json,os
from pathlib import Path
from playwright.sync_api import sync_playwright
BASE=os.environ.get('HITEL_BASE_URL','https://hitel-education-zocbo-unified-production.up.railway.app').rstrip('/')
OUT=Path('ypt-ai-captain-e2e-evidence');OUT.mkdir(exist_ok=True,parents=True)
REPORT={'base':BASE,'checks':[],'errors':[],'page_errors':[]}
def check(ok,reason):
 if not ok:raise AssertionError(reason)
 REPORT['checks'].append(reason)
def click(page,sel):page.locator(sel).first.click(timeout=25000)
def nav(page,label):page.locator('#phone .bottomnav button').filter(has_text=label).first.click(timeout=25000)
def cap(page,action):click(page,'#phone [data-captain="'+action+'"]')
def wp(page,action,value):
 click(page,'#phone [data-wp="'+action+'"][data-value="'+value+'"]')
def capture(page,name):page.screenshot(path=str(OUT/name),full_page=False)
def model(page):return page.evaluate("JSON.parse(localStorage.getItem('hitel.ypt.group-workplace.v1'))")
def captain(page):return page.evaluate("JSON.parse(localStorage.getItem('hitel.ypt.ai-captain.v1'))")
def nooverflow(page):
 return page.evaluate("document.documentElement.scrollWidth <= innerWidth+2")
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 for width in (360,390):
  ctx=browser.new_context(viewport={'width':width,'height':844},is_mobile=True,has_touch=True,locale='ko-KR',timezone_id='Asia/Seoul')
  page=ctx.new_page();page.set_default_timeout(30000)
  page.on('pageerror',lambda e:REPORT['page_errors'].append(str(e)))
  page.goto(BASE+'/?screen=groups',wait_until='domcontentloaded',timeout=65000)
  page.locator('#phone .wp-group-card').first.wait_for(timeout=45000)
  check(page.locator('#phone .bottomnav button').all_inner_texts()==['스터디그룹','질문하기','학습','족보'],"agreed 4-tab navigation "+str(width))
  check(page.evaluate("typeof window.HITEL_CAPTAIN_INSPECT==='function'"),"captain runtime loaded "+str(width))
  check(nooverflow(page),"group listing no mobile horizontal overflow "+str(width))
  wp(page,'chooseGroup','my-study')
  check('screen=groupDetail' in page.url,"study group main route "+str(width))
  check(page.locator('#phone .cap-captain').count()==1,"AI study captain dashboard visible "+str(width))
  check('AI 방장' in page.locator('#phone .cap-captain').inner_text(),"captain identified on group home "+str(width))
  check(page.locator('#phone .cap-metric').count()==3,"home homework-exam-material metrics "+str(width))
  check('월 ' in page.locator('#phone .cap-cost').inner_text(),"cost split displayed "+str(width))
  capture(page,str(width)+'-captain-home.png')
  cap(page,'startDaily')
  check('screen=groupQuestions' in page.url,"daily Socratic question opens Q&A "+str(width))
  check(captain(page)['groups']['my-study']['questions'],"proactive daily question persisted "+str(width))
  check('AI 방장' in page.locator('#phone .cap-chat').inner_text(),"daily prompt recorded by captain "+str(width))
  name='왜 일차함수의 기울기가 필요한가요 '+str(width)
  page.locator('#phone #cap-question-form [name="text"]').fill(name)
  click(page,'#phone #cap-question-form button[type="submit"]')
  chats=model(page)['chats']['my-study']
  check(any(m['by']=='나' and name in m['text'] for m in chats),"learner free question saved "+str(width))
  check(any('규칙형' in m['by'] and ('근거' in m['text'] or '반례' in m['text'] or '다른' in m['text'] or '예시' in m['text']) for m in chats),"rule-based guided Socratic followup saved "+str(width))
  capture(page,str(width)+'-captain-question.png')
  nav(page,'스터디그룹')
  wp(page,'chooseGroup','demo-five')
  check(name not in page.locator('#phone .cap-activity').inner_text(),"other group dashboard separates history "+str(width))
  nav(page,'질문하기')
  check(name not in page.locator('#phone .cap-chat').inner_text(),"group Q&A isolation "+str(width))
  nav(page,'스터디그룹')
  wp(page,'chooseGroup','my-study')
  nav(page,'학습')
  check('screen=groupLearning' in page.url,"learning nested view "+str(width))
  check(page.locator('#phone .wp-learning-tabs [data-wp="learningTab"]').count()==3,"3 learning submenus "+str(width))
  cap(page,'assignMission')
  assignment=model(page)['tasks'][0]
  check(assignment['groupId']=='my-study' and assignment.get('source')=='captain-rule-template',"captain generated a scoped mission "+str(width))
  cap(page,'openSubmission')
  page.locator('#phone #cap-submit-form [name="answer"]').fill('기울기는 x변화량에 대한 y변화량의 비율입니다.')
  click(page,'#phone #cap-submit-form button[type="submit"]')
  check(any(x['id']==assignment['id'] and x['done'] for x in model(page)['tasks']),"submitted homework completed "+str(width))
  check(assignment['id'] in captain(page)['groups']['my-study']['submissions'],"homework submission text persisted "+str(width))
  wp(page,'learningTab','materials')
  cap(page,'toggleNoteForm')
  page.locator('#phone #cap-note-form [name="title"]').fill('그룹 학습 노트 '+str(width))
  page.locator('#phone #cap-note-form [name="text"]').fill('미적분은 순간 변화율을 설명할 때 사용합니다.')
  click(page,'#phone #cap-note-form button[type="submit"]')
  check(len(captain(page)['groups']['my-study']['notes'])==1,"group-specific note stored "+str(width))
  capture(page,str(width)+'-captain-materials.png')
  wp(page,'learningTab','exams')
  click(page,'#phone [data-wp="newExam"]')
  exam_title='주간 확인시험 '+str(width)
  page.locator('#phone #wp-exam-form [name="title"]').fill(exam_title)
  page.locator('#phone #wp-exam-form [name="scope"]').fill('미적분')
  page.locator('#phone #wp-exam-form [name="date"]').fill(page.evaluate("new Date().toLocaleDateString('en-CA')"))
  click(page,'#phone #wp-exam-form button[type="submit"]')
  check(any(x['title']==exam_title and x['groupId']=='my-study' for x in model(page)['exams']),"group exam schedule persisted "+str(width))
  cap(page,'startOralExam')
  check(page.locator('#phone #cap-oral-form').count()==1,"oral assessment form opens "+str(width))
  page.locator('#phone #cap-oral-form [name="answer"]').fill('미적분은 극한을 바탕으로 변화와 누적을 구합니다.')
  click(page,'#phone #cap-oral-form button[type="submit"]')
  check(len(captain(page)['groups']['my-study']['examAnswers'])==1,"oral response preserved without fake grading "+str(width))
  capture(page,str(width)+'-captain-exams.png')
  nav(page,'스터디그룹')
  wp(page,'chooseGroup','my-study')
  click(page,'#phone [data-go="groupCaptainSettings"]')
  check('screen=groupCaptainSettings' in page.url,"AI captain settings reachable "+str(width))
  page.locator('#phone #cap-settings-form [name="dailyTime"]').fill('09:15')
  page.locator('#phone #cap-settings-form [name="budget"]').fill('60000')
  page.locator('#phone #cap-settings-form [name="reminders"]').select_option('no')
  click(page,'#phone #cap-settings-form button[type="submit"]')
  settings=captain(page)['groups']['my-study']
  check(settings['dailyTime']=='09:15' and settings['budget']==60000 and not settings['reminders'],"question schedule budget and notification preferences saved "+str(width))
  check('60,000' in page.locator('#phone .cap-cost').inner_text(),"group cost updates with settings "+str(width))
  capture(page,str(width)+'-captain-settings-result.png')
  click(page,'#phone [data-go="calendar"]')
  check('screen=calendar' in page.url,"calendar accessible in group management, not bottom nav "+str(width))
  nav(page,'족보')
  page.locator('#phone .zb-f-main-tabs button').first.wait_for(timeout=55000)
  check(page.locator('#phone .zb-f-main-tabs button').count()==6,"original six Jokbo menus retained "+str(width))
  check(page.locator('#phone iframe').count()==0,"no iframe original Jokbo "+str(width))
  check(nooverflow(page),"Jokbo mobile no horizontal overflow "+str(width))
  capture(page,str(width)+'-captain-jokbo.png')
  page.goto(BASE+'/?screen=groupDetail',wait_until='domcontentloaded')
  check('60,000' in page.locator('#phone .cap-cost').inner_text(),"AI captain settings survive reload "+str(width))
  check(page.evaluate("window.HITEL_CAPTAIN_INSPECT().groupNoteCount")==1,"captain notes survive reload "+str(width))
  check(page.evaluate("window.HITEL_CAPTAIN_INSPECT().llmConnected") is False,"no false LLM connection claim "+str(width))
  check(page.evaluate("window.HITEL_CAPTAIN_INSPECT().sharedPersistence") is False,"no false multi-user server sync claim "+str(width))
  check(nooverflow(page),"captain dashboard no mobile horizontal overflow "+str(width))
  ctx.close()
 browser.close()
(OUT/'result.json').write_text(json.dumps(REPORT,ensure_ascii=False,indent=2),encoding='utf-8')
assert not REPORT['page_errors'],REPORT['page_errors']
print('HITEL_AI_CAPTAIN_E2E_PASSED',json.dumps({'base':BASE,'checks':len(REPORT['checks']),'page_errors':REPORT['page_errors']},ensure_ascii=False),flush=True)

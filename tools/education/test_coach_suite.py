#!/usr/bin/env python3
"""Independent browser QA for complete phone-size learning workflow.
No dependence on third-party Zocbo search API. Never asserts generative AI exists."""
import os,json,base64
from pathlib import Path
from playwright.sync_api import sync_playwright
BASE=os.getenv('HITEL_BASE_URL','https://hitel-education-zocbo-unified-production.up.railway.app').rstrip('/')
OUT=Path('education-coach-mobile-evidence');OUT.mkdir(exist_ok=True,parents=True)
REPORT={'base':BASE,'checks':[],'failures':[]}
def check(cond,title):
    if not cond:raise AssertionError(title)
    REPORT['checks'].append(title)
def snap(p,width,key):p.screenshot(path=str(OUT/f'{width}-{key}.png'),full_page=False)
def suite(p):return p.evaluate("window.HITEL_COACH_INSPECT()")
def data(p):return p.evaluate("JSON.parse(localStorage.getItem('hitel.education.coach-suite.v1'))")
def db(p):return p.evaluate("JSON.parse(localStorage.getItem('hitel.ypt.group-workplace.v1'))")
def nav(p,route):p.locator(f'#phone [data-cs="route"][data-value="{route}"]').first.click()
with sync_playwright() as play:
 browser=play.chromium.launch(headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 for width in (320,360,390,430):
  ctx=browser.new_context(viewport={'width':width,'height':844},is_mobile=True,has_touch=True,locale='ko-KR',timezone_id='Asia/Seoul')
  page=ctx.new_page();errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.goto(BASE+'/?screen=groupAITutor&group=demo-five',wait_until='domcontentloaded',timeout=55000)
  page.locator('#phone .bs-books').wait_for(timeout=35000)
  check(page.locator('#phone .bottomnav button').count()==5,f'five bottom tabs {width}')
  check(page.locator('#phone .bs-books .bs-book').count()==11,f'book grid stays functional {width}')
  page.locator('#phone .bs-books .bs-book-open').first.click()
  page.locator('#phone [data-bs="go"][data-val="groupCoach"]').click()
  page.locator('#phone .cs-chat').wait_for(timeout=15000)
  check(page.locator('#phone .cs-coach-notice').count()==1,f'clearly identified rule-based coach {width}')
  check(suite(page)['llmConnected'] is False,f'no false LLM claim {width}')
  check(page.locator('#phone .cs-bubble').count()>=1,f'contextual coach intro {width}')
  page.locator('#phone [data-cs="coachQuick"][data-value="history"]').click()
  check(page.locator('#phone .cs-bubble').count()>=3,f'historical context dialogue {width}')
  page.locator('#phone #cs-message').fill('힌트가 필요합니다')
  page.locator('#phone #cs-chat-form button[type="submit"]').click()
  check(page.locator('#phone .cs-bubble').count()>=5,f'student followup coach prompt {width}')
  snap(page,width,'coach')
  nav(page,'groupPractice')
  check(page.locator('#phone .cs-problem').count()==6,f'six independent practice samples {width}')
  page.locator('#phone [data-cs="open"]').first.click()
  check('screen=groupProblemDetail' in page.url,f'problem detail route {width}')
  page.locator('#phone #cs-answer').fill('999')
  page.locator('#phone #cs-answer-form button[type="submit"]').click()
  check(page.locator('#phone .cs-result.wrong').count()==1,f'wrong result appears {width}')
  check(len(data(page)['attempts'])==1,f'wrong attempt saved {width}')
  page.locator('#phone [data-cs="hint"]').first.click()
  check(page.locator('#phone .cs-hint').count()==1,f'staged hints rendered {width}')
  # Preserve problem handwriting using mouse pointers.
  c=page.locator('#phone #cs-canvas')
  c.scroll_into_view_if_needed()
  b=c.bounding_box()
  page.mouse.move(b['x']+25,b['y']+40)
  page.mouse.down()
  page.mouse.move(b['x']+95,b['y']+83,steps=8)
  page.mouse.up()
  check(bool(data(page)['drawings']),f'handwriting saved {width}')
  tiny=base64.b64decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLttAAAAABJRU5ErkJggg==')
  page.locator('#phone #cs-file').set_input_files({'name':'question.png','mimeType':'image/png','buffer':tiny})
  page.locator('#phone .cs-upload img').wait_for(timeout=10000)
  check(suite(page)['photoOCR'] is False,f'photo preview honest no OCR {width}')
  snap(page,width,'problem')
  nav(page,'groupMistakes')
  check(page.locator('#phone .cs-mistake').count()==1,f'mistake log {width}')
  page.locator('#phone [data-cs="shareProblem"]').first.click()
  check(any('coach-' in d['id'] for d in db(page)['materials']['demo-five']),f'group sharing browser model {width}')
  page.locator('#phone [data-cs="review"]').first.click()
  check('screen=groupProblemDetail' in page.url,f'variant review opens problem {width}')
  nav(page,'groupCoachDashboard')
  check(page.locator('#phone .cs-week>div').count()==7,f'learning calendar {width}')
  check(page.locator('#phone .cs-history').count()>=1,f'recorded outcome timeline {width}')
  snap(page,width,'progress')
  nav(page,'groupPractice')
  page.locator('#phone #cs-manual-form [name="location"]').fill('30쪽 3번')
  page.locator('#phone #cs-manual-form [name="question"]').fill('내가 직접 입력한 연습문제')
  page.locator('#phone #cs-manual-form button[type="submit"]').click()
  check('screen=groupProblemDetail' in page.url,f'input user problem {width}')
  check(suite(page)['problemCount']==7,f'user entered question counted {width}')
  check(page.locator('#phone .cs-problem').inner_text().find('직접 입력')>=0,f'user question displayed {width}')
  check(page.evaluate("document.documentElement.scrollWidth <= innerWidth+2"),f'no horizontal viewport overflow {width}')
  check(len(errors)==0,f'no JS errors {width}: '+str(errors))
  REPORT.setdefault('widths',[]).append(width)
  ctx.close()
 browser.close()
(OUT/'result.json').write_text(json.dumps(REPORT,ensure_ascii=False,indent=2),encoding='utf8')
print('HITEL_COACH_ALL_BENCHMARK_MOBILE_PASSED',json.dumps({'widths':REPORT.get('widths',[]),'checks':len(REPORT['checks'])},ensure_ascii=False),flush=True)
